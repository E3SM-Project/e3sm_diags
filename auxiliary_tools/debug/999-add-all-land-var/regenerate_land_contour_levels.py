"""Regenerate lat_lon_land contour levels in the units e3sm_diags plots.

The levels added in #1007 (``generate_land_config_with_data.py``) applied a
hand-written unit conversion that does not match e3sm_diags' own
``convert_units()``, e.g. N/P fluxes in gN/m^2/day while plots are in
mgN/m^2/day, and water fluxes in mm/day while plots are in mm/s.

This script recomputes the same 5th-95th percentile levels from the fields
e3sm_diags actually plots. Those fields are the ``*_test.nc`` files written
by running the ``lat_lon_land`` set with ``save_netcdf = True`` on a model
climatology (here v3.LR.piControl years 0401-0450, ANN).

Only blocks generated by #1007 are considered, and only blocks whose levels
disagree with the regenerated range are rewritten.

Usage:
    python regenerate_land_contour_levels.py <cfg> <results_dir> <report.json>
"""

import json
import re
import sys
from pathlib import Path

import numpy as np
import xarray as xr

PI_MARKER = "# contours: 5th/95th percentiles from PI control data"
NEW_MARKER = (
    "# contours: 5th/95th percentiles of v3.LR.piControl 0401-0450 ANN "
    "in plotted units"
)
# Rewrite a block when either end of its level range is off by more than this
# fraction of the regenerated span.
TOLERANCE = 0.25
N_LEVELS = 16


def round_levels(levels: list[float]) -> list[float]:
    """Round levels using the precision rules of the #1007 generator."""
    max_abs = max(abs(min(levels)), abs(max(levels)))
    if max_abs < 1e-10:
        precision = 15
    elif max_abs < 1e-6:
        precision = 10
    elif max_abs < 1e-3:
        precision = 8
    elif max_abs < 1:
        precision = 6
    elif max_abs < 1000:
        precision = 4
    else:
        precision = 2

    return [round(x, precision) for x in levels]


def percentile_levels(values: np.ndarray) -> list[float] | None:
    """Return 16 evenly spaced levels between the 5th and 95th percentiles."""
    values = values[np.isfinite(values)]
    if values.size == 0:
        return None

    p5, p95 = np.percentile(values, [5, 95])
    if not p95 > p5:
        return None

    levels = round_levels(list(np.linspace(p5, p95, N_LEVELS)))
    if any(b <= a for a, b in zip(levels, levels[1:])):
        return None

    return levels


def format_levels(levels: list[float]) -> str:
    """Format levels so the cfg parser (yaml.safe_load) reads them as floats.

    YAML 1.1 only treats exponent notation as a float when it has a decimal
    point, so "2e-10" would be parsed as a string; write "2.0e-10" instead.
    """
    tokens = []
    for x in levels:
        s = f"{x:.6g}"
        if "e" in s and "." not in s:
            s = s.replace("e", ".0e", 1)
        tokens.append(s)

    return "[" + ",".join(tokens) + "]"


def main(cfg_path: str, results_dir: str, report_path: str) -> None:
    text = Path(cfg_path).read_text()
    blocks = text.split("[#]")
    report = []

    for i, block in enumerate(blocks):
        if PI_MARKER not in block:
            continue

        var = re.search(r'^variables = \["([^"]+)"\]', block, re.M).group(1)
        case_id = re.search(r'^case_id = "([^"]+)"', block, re.M).group(1)
        old_match = re.search(r"^contour_levels = \[(.*)\]$", block, re.M)
        entry = {"var": var, "case_id": case_id}

        # Blocks without hardcoded levels already use auto levels, some on
        # purpose (e.g. GC_HEAT1 in #1067), so leave them alone.
        if old_match is None:
            entry["status"] = "auto levels, unchanged"
            report.append(entry)
            continue

        nc = Path(results_dir, "lat_lon_land", case_id).glob(f"*-{var}-ANN-global_test.nc")
        nc = next(nc, None)
        if nc is None:
            entry["status"] = "no plotted data"
            report.append(entry)
            continue

        with xr.open_dataset(nc) as ds:
            da = ds[var] if var in ds else ds[list(ds.data_vars)[0]]
            units = da.attrs.get("units", "")
            new = percentile_levels(da.values.ravel())

        entry["units"] = units
        if new is None:
            entry["status"] = "degenerate data, unchanged"
            report.append(entry)
            continue

        old = [float(x) for x in old_match.group(1).split(",")]
        entry.update(old=old, new=new)
        span = new[-1] - new[0]
        if (
            abs(old[0] - new[0]) <= TOLERANCE * span
            and abs(old[-1] - new[-1]) <= TOLERANCE * span
        ):
            entry["status"] = "consistent, unchanged"
            report.append(entry)
            continue

        block = block.replace(old_match.group(0), f"contour_levels = {format_levels(new)}")
        block = block.replace(PI_MARKER, NEW_MARKER)
        block = re.sub(r"^# target_units: .*$", f"# target_units: {units}", block, flags=re.M)
        block = re.sub(r"^# conversion_factor: .*\n", "", block, flags=re.M)
        blocks[i] = block
        entry["status"] = "rewritten"
        report.append(entry)

    Path(cfg_path).write_text("[#]".join(blocks))
    Path(report_path).write_text(json.dumps(report, indent=1))

    counts: dict[str, int] = {}
    for entry in report:
        counts[entry["status"]] = counts.get(entry["status"], 0) + 1
    print(counts)


if __name__ == "__main__":
    main(*sys.argv[1:4])
